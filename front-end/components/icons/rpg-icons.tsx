type Layer = readonly [keyof typeof palette, string];
export type RpgIconProps = SVGProps<SVGSVGElement> & { size?: number | string };

function createIcon(name: string, layers: readonly Layer[], rotate = 0) {
  const Icon = forwardRef<SVGSVGElement, RpgIconProps>(function RpgIcon({ size = 20, className, children, ...props }, ref) {
    return (
      <svg ref={ref} width={size} height={size} viewBox="0 0 20 20" fill="none"
        shapeRendering="crispEdges" focusable="false" aria-hidden={props["aria-label"] ? undefined : true}
        role={props["aria-label"] ? "img" : undefined} className={cn("shrink-0", className)} {...props}
        data-rpg-icon={name}>
        <g transform={rotate ? `rotate(${rotate} 10 10)` : undefined}>
          {layers.map(([paint, d], index) => <path key={index} d={d} fill={palette[paint]} />)}
        </g>
        {children}
      </svg>
    );
  });
  Icon.displayName = `Rpg${name}`;
  return Icon;
}

